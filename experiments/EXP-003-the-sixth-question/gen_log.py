#!/usr/bin/env python3
"""
gen_log.py — emit ENGINEERING-LOG.md's machine section from the records.

The symposium's finding 2: incidents are *generated*, not typed, because a
hand-maintained log drifts within a week. This is that generator, and running it
is the test of the finding — if the entries below cannot be derived, the finding
was wishful and should be struck rather than aspired to.

It has a start date, and the start date is not the start of the experiment.
Pilot 1 was collected through the harness and carries no timestamps, no token
counts, no echoed model id, and no error records. Nothing before pilot 2 is
derivable, so nothing before pilot 2 is generated: those entries are written by
hand and marked `reconstructed`. That boundary is not a limitation of this
script. It is the finding.

Sources
  incidents/*.json   failed or non-subject calls (stop_reason == "error")
  raw2/*.json        pilot-2 subject calls
Both are written by collect.js, which records what it sent and what came back.

Usage:  python3 gen_log.py            # markdown to stdout
"""
import json
import glob
import os
import re
from collections import Counter

INCIDENTS = "incidents"
RAWS = "raw2"


def load(pattern):
    """Prefix files (*.messages.json) live alongside call records and are message
    ARRAYS, not calls. They are excluded here rather than defended against at every
    use site — a shape check belongs where the shapes are decided."""
    out = []
    for f in sorted(glob.glob(pattern)):
        if f.endswith(".messages.json"):
            continue
        try:
            out.append((f, json.load(open(f))))
        except Exception as e:                       # a malformed record is itself
            out.append((f, {"_unreadable": str(e)}))  # a fact about the run
    return out


def classify(err):
    """Cause taxonomy. Deliberately admits a non-technical value: the OAuth
    decision's cause is that the clean path was unaffordable, and a schema with
    no room for that silently launders it into 'chose OAuth for simplicity'."""
    e = (err or "").lower()
    if "oauth_not_allowed_for_organization" in e:
        return "provider-policy"
    if "429" in e or "rate" in e:
        return "provider-capacity"
    if "401" in e or "403" in e or "authentication" in e:
        return "credential"
    if "timeout" in e or "econnreset" in e:
        return "network"
    return "technical"


def entry(f, r):
    """One incident → one log entry."""
    ts = (r.get("ts") or "")[:19].replace("T", " ")
    err = r.get("error") or ""
    cause = classify(err)
    # the provider's own message, verbatim — not our paraphrase of it
    m = re.search(r'"message":"([^"]+)"', err)
    said = m.group(1) if m else err.split("\n")[0][:160]
    code = re.search(r'"error_code":"([^"]+)"', err)
    lines = [
        f"### {ts} UTC · {cause}",
        "",
        f"- **cell** `{r.get('cell','—')}` item `{r.get('item','—')}`"
        f"  ·  **auth** {r.get('auth_mode','—')}",
        f"- **provider said** “{said}”"
        + (f" (`{code.group(1)}`)" if code else ""),
        f"- **served** {r.get('served_model') or '— nothing was served'}"
        f"  ·  **stop** `{r.get('stop_reason','—')}`"
        f"  ·  **{r.get('duration_ms','—')} ms**",
        f"- **record** `{f}`",
        "- **provenance** witnessed (written by the instrument at the time)",
    ]
    return "\n".join(lines)


def main():
    inc = load(f"{INCIDENTS}/*.json")
    raws = load(f"{RAWS}/*.json")

    print("<!-- GENERATED by gen_log.py — do not hand-edit below this line. -->")
    print("<!-- Entries above the marker are written and marked `reconstructed`. -->")
    print()

    if not inc and not raws:
        print("*No machine-recorded events yet. The generated section begins with "
              "pilot 2; everything before it is written by hand and marked "
              "`reconstructed`, because the harness-collected records carry no "
              "timestamps, token counts, errors, or echoed model id.*")
        return

    # Not every file in incidents/ is a failed call. An aborted trunk leaves its
    # partial message array here too — quarantined so nothing can fork from it.
    # The generator must survive that rather than crash on the first one.
    quarantined = [(f, r) for f, r in inc if not isinstance(r, dict)]
    inc = [(f, r) for f, r in inc if isinstance(r, dict)]

    if inc:
        print(f"## Incidents ({len(inc)})")
        print()
        print("Calls that produced no subject data. They live in `incidents/` "
              "rather than `raw2/` because a failure record and an answer record "
              "are different kinds of thing, and a directory that holds both "
              "will eventually be read as though it holds one.")
        print()
        for f, r in inc:
            print(entry(f, r))
            print()

    if quarantined:
        print(f"## Quarantined artefacts ({len(quarantined)})")
        print()
        for f, r in quarantined:
            print(f"- `{f}` — {len(r)} messages, retained but not forkable")
        print()

    if raws:
        ok = [r for _, r in raws if not r.get("error")]
        toks = Counter()
        for r in ok:
            u = r.get("usage") or {}
            for k in ("input_tokens", "output_tokens", "cache_read_input_tokens"):
                toks[k] += u.get(k) or 0
        models = sorted({r.get("served_model") for r in ok if r.get("served_model")})
        ts = sorted((r.get("ts") or "") for _, r in raws if r.get("ts"))
        print(f"## Collection · {len(raws)} calls")
        print()
        print(f"- **span** {ts[0][:19]} → {ts[-1][:19]} UTC" if ts else "- span —")
        print(f"- **served** {', '.join(models) or '—'}"
              "  ·  echoed by the API, not declared by us")
        print(f"- **tokens** {toks['input_tokens']:,} in · "
              f"{toks['output_tokens']:,} out · "
              f"{toks['cache_read_input_tokens']:,} cached")
        print(f"- **errors** {len(raws) - len(ok)}")
        print()


if __name__ == "__main__":
    main()
